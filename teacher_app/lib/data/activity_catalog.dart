    emoji: emoji,
    imageAlt: 'Ilustração de $word',
    librasHint: 'LETRA: desenhar a letra no ar, depois tocar na carta.',
    steps: ['Olhe a palavra', 'Ouça o som inicial', 'Toque na letra'],
    choices: [
      for (final letter in letters)
        ActivityChoice(
          id: letter,
          label: letter,
          emoji: letter,
          audioText: 'Letra $letter',
          isCorrect: letter == correct,
          scoreValue: letter == correct ? 1 : 0,
        ),
    ],
  );
}
