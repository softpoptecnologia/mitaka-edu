  return ActivityItem(
    id: 'let-$word',
    layout: PromptLayout.letterSelect,
    prompt: 'Qual letra começa a palavra $word?',
    promptShort: '$word começa com qual letra?',
    audioText: '$word. Qual letra você ouve no começo de $word?',
